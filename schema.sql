-- Run this in Supabase SQL Editor. Then create an admin user in Authentication > Users.
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  short_name text,
  created_at timestamptz default now()
);
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  team1 text not null,
  team2 text not null,
  match_time timestamptz not null,
  venue text default 'Chagantivaripalem',
  status text not null default 'Upcoming' check (status in ('Upcoming','Completed')),
  result text,
  created_at timestamptz default now()
);
create table if not exists public.points_table (
  id bigint generated by default as identity primary key,
  team_name text not null unique,
  played integer not null default 0,
  won integer not null default 0,
  lost integer not null default 0,
  points integer not null default 0
);
alter table public.teams enable row level security;
alter table public.matches enable row level security;
alter table public.points_table enable row level security;
-- Anyone can view public tournament information.
create policy "public read teams" on public.teams for select using (true);
create policy "public read matches" on public.matches for select using (true);
create policy "public read points" on public.points_table for select using (true);
-- Only signed-in admins can change information. For a private admin-only league site,
-- use a dedicated Supabase project and create admin accounts yourself.
create policy "admins manage teams" on public.teams for all to authenticated using (true) with check (true);
create policy "admins manage matches" on public.matches for all to authenticated using (true) with check (true);
create policy "admins manage points" on public.points_table for all to authenticated using (true) with check (true);
-- Live scoreboard: admins publish score updates; visitors can read the latest row.
create table if not exists public.live_scores (
  id bigint generated by default as identity primary key,
  match_title text not null,
  batting_team text not null,
  runs integer not null default 0,
  wickets integer not null default 0 check (wickets between 0 and 10),
  overs text not null default '0.0',
  target integer,
  status text not null default 'Live' check (status in ('Live','Upcoming','Completed')),
  run_rate text,
  note text,
  updated_at timestamptz not null default now()
);
alter table public.live_scores enable row level security;
create policy "public read live scores" on public.live_scores for select using (true);
create policy "admins manage live scores" on public.live_scores for all to authenticated using (true) with check (true);
